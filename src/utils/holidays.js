/**
 * 判断指定日期是否为非工作日（节假日或周末）
 * - 调休上班日 → 工作日（即使在周末）
 * - 法定节假日 → 非工作日
 * - 周末（周六/周日）→ 非工作日
 * @param {string} dateStr - 日期字符串 YYYY-MM-DD 或 YYYY/MM/DD
 * @returns {boolean}
 */
export const isNonWorkDay = (dateStr) => {
  const normalized = dateStr.replace(/\//g, '-')
  if (ALL_MAKEUP_WORKDAYS.has(normalized)) return false
  if (ALL_HOLIDAYS.has(normalized)) return true
  const d = new Date(normalized)
  const day = d.getDay()
  return day === 0 || day === 6
}

/**
 * 判断指定日期是否为法定节假日（不含周末）
 * @param {string} dateStr - YYYY-MM-DD 或 YYYY/MM/DD
 * @returns {boolean}
 */
export const isStatutoryHoliday = (dateStr) => {
  const normalized = dateStr.replace(/\//g, '-')
  return ALL_HOLIDAYS.has(normalized)
}
